_WORD = r"[а-яёa-z0-9-]*"
_ABBREVIATIONS = (
    (re.compile(r"\bобл\.?(?=\s|$)"), "область"),
    (re.compile(r"\bресп\.?(?=\s|$)"), "республика"),
    (re.compile(r"\bа\.?\s?о\.?(?=\s|$)|\bао\b"), "автономный округ"),
)
_CITY_PREFIX = re.compile(r"^(?:г\.|г\s|город\s|пгт\.?\s|пос\.\s|с\.\s|ст-ца\s|станица\s)\s*", re.IGNORECASE)


def _stem_regex(stem: str) -> re.Pattern[str]:
    body = (_WORD + r"\s+").join(re.escape(w) for w in stem.split())
    return re.compile(r"(?<![а-яёa-z0-9])" + body)


_PATTERNS: dict[str, tuple[tuple[int, re.Pattern[str]], ...]] = {
    name: tuple((len(s), _stem_regex(s)) for s in stems) for name, stems in REGION_STEMS.items()
}
_BY_NAME = {name.lower().replace("ё", "е"): name for name in REGION_STEMS}


def _simplify(value: str) -> str:
    text = re.sub(r"[\"«»]", " ", value.lower().replace("ё", "е"))
    text = re.sub(r"\s*[—–]\s*", " — ", text)
    for pattern, full in _ABBREVIATIONS:
        text = pattern.sub(full, text)
    return re.sub(r"\s+", " ", text).strip()


def normalize_region(value: str | None) -> str | None:
    """«Свердловская обл.», «СВЕРДЛОВСКАЯ ОБЛАСТЬ», «г. Москва» -> the official name. The longest
    matching stem wins («Московская обл.» is the oblast, not the city). Unknown spellings are kept."""
    if value is None or not value.strip():
        return None
    text = _simplify(value)
    if text in _BY_NAME:
        return _BY_NAME[text]
    best: tuple[int, str] | None = None
    for name, pats in _PATTERNS.items():
        for length, pattern in pats:
            if pattern.search(text) and (best is None or length > best[0]):
                best = (length, name)
    return best[1] if best else value.strip()


def normalize_city(value: str | None) -> str | None:
    """«г. Москва», «Г  Москва», «город Казань», «Мск "Юг"» -> «Москва», «Казань», «Мск Юг»."""
    if value is None:
        return None
    city = re.sub(r"\s+", " ", _CITY_PREFIX.sub("", re.sub(r"[\"«»]", " ", value).strip())).strip()
    return city or None
